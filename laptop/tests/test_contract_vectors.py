@pytest.mark.parametrize("v", of_kind("cmd"), ids=[
    f.get("line", "") or "<empty>" for f in of_kind("cmd")
])
def test_a_command_line_is_read_the_same_way(v):
    """Every line in the corpus, parsed by both sides.

    The simulator has to refuse exactly what the Pico refuses: a dry run
    that accepted a line the real firmware rejects would let a bad command
    through to the bench untested.
    """
    command = sim.parse_command(v["line"])

    assert command.err.value == v["err"]
    # The C++ writes NONE where there is nothing; Python leaves it empty.
    assert (command.verb or "NONE") == v["verb"]
    assert (command.axis or "NONE") == v["axis"]
    assert command.id == int(v["id"])
    assert command.mdps == int(v["mdps"])
    assert command.mdeg == int(v["mdeg"])
    assert command.has_mdeg == (v["has_mdeg"] == "1")
    assert command.gpio == int(v["gpio"])
    assert command.level == int(v["level"])


# What the laptop builds has to be a line the firmware accepts, and the
# corpus above is the proof. Each case here names the exact string, and the
# test checks both that protocol.py still produces it and that the firmware
# read it as intended - if either side changes its mind, this fails.
BUILDERS = [
    (lambda: p.move(7, "AZ", 5.0, 45.0), "MOVE,7,AZ,5000,45000"),
    (lambda: p.move(1, "AZ", 5.0, -45.0), "MOVE,1,AZ,5000,-45000"),
    (lambda: p.move(2, "el", 90.0, 10.0), "MOVE,2,EL,90000,10000"),
    (lambda: p.move(65535, "AZ", 0.1, 0.001), "MOVE,65535,AZ,100,1"),
    (lambda: p.stop(1), "STOP,1"),
    (lambda: p.estop(2), "ESTOP,2"),
    (lambda: p.zero(3, "ALL"), "ZERO,3,ALL"),
    (lambda: p.zero(4, "AZ"), "ZERO,4,AZ"),
    (lambda: p.zero(5, "EL"), "ZERO,5,EL"),
    (lambda: p.zero(6, "ALL", 90.0), "ZERO,6,ALL,90000"),
    (lambda: p.zero(7, "AZ", -10.0), "ZERO,7,AZ,-10000"),
    (lambda: p.pos(8), "POS,8"),
    (lambda: p.pin(9, 13, 1), "PIN,9,13,1"),
    (lambda: p.pin(10, 15, 0), "PIN,10,15,0"),
    (lambda: p.limits(11), "LIMITS,11"),
    (lambda: p.ping(12), "PING,12"),
]


@pytest.mark.parametrize(
    "build, expected", BUILDERS, ids=[want for _, want in BUILDERS]
)
def test_what_the_laptop_builds_is_what_the_firmware_expects(build, expected):
    assert build() == expected

    matching = [v for v in of_kind("cmd") if v["line"] == expected]
    assert matching, (
        f"{expected!r} is not in the vectors file, so nothing proves the "
        "firmware accepts it. Add it to cmd_vectors() in "
        "gen_motor_vectors.cpp and regenerate."
    )
    assert matching[0]["err"] == "none", (
        f"the firmware refuses {expected!r} with {matching[0]['err']}"
    )


def test_every_command_the_laptop_can_build_is_covered():
    # A builder added to protocol.py with no vector would be untested
    # against the firmware, which is the gap this whole file exists to
    # close.
    built = {want for _, want in BUILDERS}
    verbs = {line.split(",")[0] for line in built}
    assert verbs == {"MOVE", "STOP", "ESTOP", "ZERO", "POS", "PIN",
                     "LIMITS", "PING"}


# ============================================================================
# What the firmware decides to do about a command
# ============================================================================
# Until 7.9b these rules lived in motor_main.cpp and could not be reached
# from a host test, so nothing checked that the simulator refused the same
# things the Pico refuses. That was the one gap named when the contract
# test was written, and this closes it.


def _state_of(v):
    """Build a simulator in the state the vector describes."""
    machine = sim.MotorSim(
        version="abc1234", target="gs_motor", boot_us=0
    )
    machine.az.zeroed = v["az_zeroed"] == "1"
    machine.el.zeroed = v["el_zeroed"] == "1"
    machine.az.pos_steps = int(v["az_pos_steps"])
    machine.el.pos_steps = int(v["el_pos_steps"])
    return machine


@pytest.mark.parametrize(
    "v",
    of_kind("decide"),
    ids=[
        f"{f['cmd']}-busy{f['busy']}-az{f['az_zeroed']}el{f['el_zeroed']}"
        for f in of_kind("decide")
    ],
)
def test_the_same_command_is_answered_the_same_way(v):
    machine = _state_of(v)
    command = sim.parse_command(_unescape(v["cmd"]))

    out = []
    machine._handle(
        command, v["busy"] == "1", int(v["uptime_ms"]) * 1000, out
    )

    expected = [line for line in (v["line1"], v["line2"]) if line]
    assert out == [_unescape(line) for line in expected]


@pytest.mark.parametrize(
    "v",
    [f for f in of_kind("decide") if f["act"] == "setpin"],
    ids=[
        f"{f['cmd']}-gpio{f['gpio']}"
        for f in of_kind("decide")
        if f["act"] == "setpin"
    ],
)
def test_poking_a_pin_costs_the_same_zero_on_both_sides(v):
    # Driving a step line makes the driver take a step nobody counted, so
    # that axis gives up its zero. A simulator that kept it would let a
    # dry run move from a position the real machine no longer knows.
    machine = _state_of(v)
    was_az, was_el = machine.az.zeroed, machine.el.zeroed

    machine._handle(sim.parse_command(_unescape(v["cmd"])), False, 0, [])

    assert machine.az.zeroed == (was_az and v["clear_az_zero"] != "1")
    assert machine.el.zeroed == (was_el and v["clear_el_zero"] != "1")


@pytest.mark.parametrize(
    "v",
    [f for f in of_kind("decide") if f["act"] == "setzero"],
    ids=[
        f"{f['cmd']}" for f in of_kind("decide") if f["act"] == "setzero"
    ],
)
def test_zeroing_places_the_axes_at_the_same_steps(v):
    machine = _state_of(v)
    machine._handle(sim.parse_command(_unescape(v["cmd"])), False, 0, [])

    if v["zero_az"] == "1":
        assert machine.az.pos_steps == int(v["az_steps"])
        assert machine.az.zeroed
    if v["zero_el"] == "1":
        assert machine.el.pos_steps == int(v["el_steps"])
        assert machine.el.zeroed


def test_a_move_is_only_started_when_the_firmware_would_start_one():
    # The act field says whether the Pico actually set an axis going.
    # Anything the simulator starts and the firmware does not is a dry run
    # that moves a machine the real one leaves still.
    for v in of_kind("decide"):
        machine = _state_of(v)
        machine._handle(
            sim.parse_command(_unescape(v["cmd"])),
            v["busy"] == "1",
            int(v["uptime_ms"]) * 1000,
            [],
        )
        started = machine.az.moving or machine.el.moving
        assert started == (v["act"] == "startmove"), (
            f"{v['cmd']!r} with busy={v['busy']}: firmware act={v['act']}, "
            f"simulator {'started' if started else 'did not start'} a move"
        )
