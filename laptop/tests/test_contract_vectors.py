def test_the_limits_match_the_firmware_this_was_built_from():
    # The one vector that is about configuration rather than format: if
    # somebody widens elevation in motor_config.hpp, the simulator must be
    # widened with it or every dry run is rehearsing the wrong machine.
    (v,) = _reply("lim")

    assert sim.AZ_SPEC.min_mdeg == int(v["az_min_mdeg"])
    assert sim.AZ_SPEC.max_mdeg == int(v["az_max_mdeg"])
    assert sim.EL_SPEC.min_mdeg == int(v["el_min_mdeg"])
    assert sim.EL_SPEC.max_mdeg == int(v["el_max_mdeg"])
    assert sim.SPEED_MIN_MDPS == int(v["speed_min_mdps"])
    assert sim.SPEED_MAX_MDPS == int(v["speed_max_mdps"])

    assert sim._lim(int(v["id"])) == v["line"]


@pytest.mark.parametrize("v", _reply("pong"), ids=_ids("pong", "id"))
def test_pong(v):
    version = _unescape(v["version_in"])
    line = sim._pong(int(v["id"]), v["target"], version, int(v["uptime_ms"]))
    assert line == v["line"]

    record = p.parse_reply(v["line"])
    assert isinstance(record, p.Pong)
    assert record.uptime_ms == int(v["uptime_ms"])
    # What comes back is the cleaned-up version string, not what went in:
    # a comma would have split the line into an extra field.
    assert record.version == sim.sanitise_token(version)


