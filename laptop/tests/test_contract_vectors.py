@pytest.mark.parametrize("v", _reply("err"), ids=_ids("err", "id", "code"))
def test_err(v):
    detail = _unescape(v["detail_in"])
    assert sim._err(int(v["id"]), v["code"], detail) == v["line"]

    record = p.parse_reply(v["line"])
    assert isinstance(record, p.Err)
    assert record.code == v["code"]
    assert record.detail == sim.sanitise_token(detail)
    # Every code the firmware can send has something to say to the
    # operator. A new one added on that side with no entry here would
    # print as a bare word.
    assert record.code in p.ERR_MEANING


