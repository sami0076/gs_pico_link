"""The contract: the Python must agree with the C++, line for line.

The motor protocol is written twice - in C++ on the Pico and in Python
here - and two implementations of one format drift apart. Quietly, and the
first sign is a bench day where the numbers are wrong in a way nobody can
explain.

So `firmware/host_tests/gen_motor_vectors.cpp` runs the firmware's own code
and writes down what came out. Everything below holds the Python to that
file. Nothing here is checked against anything Python produced: every
expected value came from the C++.

    data/motor_vectors.txt      what the firmware did
    gs/protocol.py              must read those lines back
    gs/motor_sim.py             must produce those same lines

Keeping it current
------------------

The file is checked in because the C++ builds in WSL and this runs on
Windows. `ctest` regenerates it and compares, so a change made to the
firmware and not regenerated fails there. If these tests fail after a
firmware change, regenerate first and look at the diff - that diff is the
protocol change, stated plainly.

    cmake -S firmware/host_tests -B ~/build/gs-host -G Ninja
    ninja -C ~/build/gs-host
    ~/build/gs-host/gen_motor_vectors laptop/tests/data/motor_vectors.txt
"""

from __future__ import annotations

import pathlib

import pytest

from gs import motor_sim as sim
from gs import protocol as p

VECTORS = pathlib.Path(__file__).parent / "data" / "motor_vectors.txt"

# Bumped in the generator when the shape of the file changes. An old file
# read as though it were a new one would quietly test nothing.
EXPECTED_FORMAT_VERSION = 1


def _unescape(text: str) -> str:
    """Put back the characters the generator had to escape to write them."""
    out = []
    i = 0
    while i < len(text):
        if text[i] == "\\" and i + 1 < len(text):
            nxt = text[i + 1]
            out.append({"n": "\n", "r": "\r", "t": "\t", "\\": "\\"}[nxt])
            i += 2
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def _load():
    """The file as a list of (kind, fields) and the count it claims."""
    if not VECTORS.exists():
        raise AssertionError(
            f"{VECTORS} is missing. It is generated by "
            "firmware/host_tests/gen_motor_vectors.cpp and checked in; see "
            "this file's docstring."
        )

    records = []
    version = None
    claimed = None

    # Read as bytes and split on \n: the file is written with LF endings on
    # every platform, and letting Python's text mode translate them would
    # hide a file that had been rewritten by something on the way past.
    for raw in VECTORS.read_bytes().split(b"\n"):
        line = raw.decode("ascii")
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if parts[0] == "version":
            version = int(parts[1])
            continue
        if parts[0] == "count":
            claimed = int(parts[1])
            continue

        fields = {}
        for piece in parts[1:]:
            key, _, value = piece.partition("=")
            fields[key] = value
        records.append((parts[0], fields))

    assert version == EXPECTED_FORMAT_VERSION, (
        f"vectors file is version {version}, this test expects "
        f"{EXPECTED_FORMAT_VERSION}"
    )
    return records, claimed


RECORDS, CLAIMED_COUNT = _load()


def of_kind(kind):
    return [fields for name, fields in RECORDS if name == kind]


def ids_for(kind, *keys):
    """Readable test names, so a failure says which vector broke."""
    return [
        "-".join(str(f.get(k, "")) for k in keys) for f in of_kind(kind)
    ]


# ============================================================================
# The file itself
# ============================================================================


def test_the_file_is_whole():
    # A truncated file would silently test less than it looks like it does.
    assert CLAIMED_COUNT == len(RECORDS), (
        f"the file says it holds {CLAIMED_COUNT} vectors but "
        f"{len(RECORDS)} were read - it looks truncated"
    )
    assert len(RECORDS) > 200, "suspiciously few vectors"


def test_every_kind_of_vector_is_present():
    kinds = {name for name, _ in RECORDS}
    assert kinds == {"conv", "plan", "interval", "reply", "cmd", "decide"}


