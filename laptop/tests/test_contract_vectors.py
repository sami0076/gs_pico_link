@pytest.mark.parametrize(
    "v", of_kind("conv"), ids=ids_for("conv", "dir", "axis", "mdeg", "steps")
)
def test_steps_and_angles_convert_the_same_way(v):
    # The record says which way round the firmware converted. Checking
    # only that one direction matters: the two are deliberately not
    # inverses of each other, since most angles do not land on a step.
    spec = sim.AZ_SPEC if v["axis"] == "AZ" else sim.EL_SPEC

    if v["dir"] == "to_steps":
        assert sim.mdeg_to_steps(spec, int(v["mdeg"])) == int(v["steps"])
    else:
        assert sim.steps_to_mdeg(spec, int(v["steps"])) == int(v["mdeg"])


