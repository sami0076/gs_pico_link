def test_the_gap_between_pulses_is_the_same(v):
    spec = sim.AZ_SPEC if v["axis"] == "AZ" else sim.EL_SPEC
    _, m = sim.plan_move(spec, 0, int(v["delta_mdeg"]), int(v["speed_mdps"]))

    assert sim.interval_us(m, int(v["i"])) == int(v["interval_us"])


